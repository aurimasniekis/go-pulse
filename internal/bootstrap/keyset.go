package bootstrap

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/x509"
	"encoding/json"
	"encoding/pem"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"time"

	"github.com/nats-io/nkeys"

	"github.com/aurimasniekis/go-pulse/internal/certs"
	"github.com/aurimasniekis/go-pulse/internal/natsauth"
	"github.com/aurimasniekis/go-pulse/internal/secretbox"
)

const keySetVersion = 1

// KeySet is the sealed content of keys.enc (PL-KEY-001). Seeds are nkeys seeds; PEM fields hold private keys.
type KeySet struct {
	Version         int       `json:"v"`
	CreatedAt       time.Time `json:"created_at"`
	Operator        string    `json:"operator"`
	OperatorSigning string    `json:"operator_signing"`
	SysAccount      string    `json:"sys_account"`
	SysSigning      string    `json:"sys_signing"`
	AppAccount      string    `json:"app_account"`
	AppSigning      string    `json:"app_signing"`
	SysUserSeed     string    `json:"sys_user"`
	AppUserSeed     string    `json:"app_user"`
	CACert          string    `json:"ca_cert"`
	CAKey           string    `json:"ca_key"`
	ACMEAccountKey  string    `json:"acme_account_key"`
	// OperatorJWT and SysAccountJWT are kept so re-running init renders byte-identical files.
	OperatorJWT   string `json:"operator_jwt"`
	SysAccountJWT string `json:"sys_account_jwt"`
}

// ErrNoKeySet means keys.enc does not exist yet (run `pulsed init`).
var ErrNoKeySet = errors.New("bootstrap: keys.enc not found; run `pulsed init` first")

// LoadKeySet opens keys.enc with the master key.
func LoadKeySet(path string, master []byte) (*KeySet, error) {
	blob, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNoKeySet
	}
	if err != nil {
		return nil, err
	}
	pt, err := secretbox.Open(master, blob)
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", path, err)
	}
	var ks KeySet
	if err := json.Unmarshal(pt, &ks); err != nil {
		return nil, fmt.Errorf("decode key set: %w", err)
	}
	if ks.Version > keySetVersion {
		return nil, fmt.Errorf("key set version %d is newer than this binary supports (%d)", ks.Version, keySetVersion)
	}
	return &ks, nil
}

// Save seals and atomically writes the key set (0600).
func (ks *KeySet) Save(path string, master []byte) error {
	pt, err := json.Marshal(ks)
	if err != nil {
		return err
	}
	blob, err := secretbox.Seal(master, pt)
	if err != nil {
		return err
	}
	return secretbox.WriteFileAtomic(path, blob, 0o600)
}

// fill generates any missing key and reports whether something changed. Existing keys are never replaced.
func (ks *KeySet) fill(now time.Time) (bool, error) {
	changed := false
	gen := func(field *string, create func() (nkeys.KeyPair, error)) error {
		if *field != "" {
			return nil
		}
		kp, err := create()
		if err != nil {
			return err
		}
		seed, err := kp.Seed()
		if err != nil {
			return err
		}
		*field = string(seed)
		changed = true
		return nil
	}
	if ks.Version == 0 {
		ks.Version = keySetVersion
		ks.CreatedAt = now.UTC()
		changed = true
	}
	for _, g := range []struct {
		f *string
		c func() (nkeys.KeyPair, error)
	}{
		{&ks.Operator, nkeys.CreateOperator}, {&ks.OperatorSigning, nkeys.CreateOperator},
		{&ks.SysAccount, nkeys.CreateAccount}, {&ks.SysSigning, nkeys.CreateAccount},
		{&ks.AppAccount, nkeys.CreateAccount}, {&ks.AppSigning, nkeys.CreateAccount},
		{&ks.SysUserSeed, nkeys.CreateUser}, {&ks.AppUserSeed, nkeys.CreateUser},
	} {
		if err := gen(g.f, g.c); err != nil {
			return false, err
		}
	}
	if ks.CACert == "" || ks.CAKey == "" {
		ca, err := certs.NewCA("pulse internal CA", now)
		if err != nil {
			return false, err
		}
		ks.CACert, ks.CAKey = string(ca.CertPEM), string(ca.KeyPEM)
		changed = true
	}
	if ks.ACMEAccountKey == "" {
		k, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			return false, err
		}
		der, err := x509.MarshalECPrivateKey(k)
		if err != nil {
			return false, err
		}
		ks.ACMEAccountKey = string(pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: der}))
		changed = true
	}
	if ks.OperatorJWT == "" || ks.SysAccountJWT == "" {
		if err := ks.encodeStaticJWTs(); err != nil {
			return false, err
		}
		changed = true
	}
	return changed, nil
}

func (ks *KeySet) encodeStaticJWTs() error {
	op, opSign := ks.MustKP(ks.Operator), ks.MustKP(ks.OperatorSigning)
	sysPub, sysSignPub := ks.Pub(ks.SysAccount), ks.Pub(ks.SysSigning)
	opJWT, err := natsauth.OperatorJWT(op, opSign, sysPub)
	if err != nil {
		return err
	}
	sysJWT, err := natsauth.EncodeAccount(natsauth.SysAccountClaims(sysPub, sysSignPub), opSign)
	if err != nil {
		return err
	}
	ks.OperatorJWT, ks.SysAccountJWT = opJWT, sysJWT
	return nil
}

// MustKP parses a seed from the key set. Seeds are generated by this package, so failure means a corrupted key set.
func (ks *KeySet) MustKP(seed string) nkeys.KeyPair {
	kp, err := nkeys.FromSeed([]byte(seed))
	if err != nil {
		panic(fmt.Sprintf("bootstrap: corrupted seed in key set: %v", err))
	}
	return kp
}

// Pub returns the public key for a seed in the key set.
func (ks *KeySet) Pub(seed string) string {
	pub, err := ks.MustKP(seed).PublicKey()
	if err != nil {
		panic(fmt.Sprintf("bootstrap: corrupted seed in key set: %v", err))
	}
	return pub
}

// CA returns the internal CA.
func (ks *KeySet) CA() (*certs.CA, error) { return certs.LoadCA([]byte(ks.CACert), []byte(ks.CAKey)) }

// Internal user names.
const (
	SysUserName = "pulsed-sys"
	AppUserName = "pulsed-app"
)

// SysUser mints the JWT for pulsed's SYS account user and returns it with the user seed.
func (ks *KeySet) SysUser() (string, []byte, error) {
	return ks.internalUser(ks.SysUserSeed, ks.SysAccount, ks.SysSigning, SysUserName)
}

// AppUser mints the JWT for pulsed's APP account user (unrestricted) and returns it with the user seed.
func (ks *KeySet) AppUser() (string, []byte, error) {
	return ks.internalUser(ks.AppUserSeed, ks.AppAccount, ks.AppSigning, AppUserName)
}

func (ks *KeySet) internalUser(userSeed, accountSeed, signingSeed, name string) (string, []byte, error) {
	tok, err := natsauth.UserJWT(ks.Pub(userSeed), ks.Pub(accountSeed), ks.MustKP(signingSeed), natsauth.UserOptions{Name: name})
	if err != nil {
		return "", nil, err
	}
	return tok, []byte(userSeed), nil
}
