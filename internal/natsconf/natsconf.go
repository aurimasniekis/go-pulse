// Package natsconf renders nats.conf for operator mode with the full resolver (PL-KEY-004, ADR-0006).
package natsconf

import (
	"bytes"
	"errors"
	"fmt"
	"strconv"
	"text/template"
)

// Params are the inputs for nats.conf. Paths are as seen by the nats container.
type Params struct {
	ServerName      string
	ClientListen    string // e.g. 0.0.0.0:4222
	MonitorListen   string // e.g. 0.0.0.0:8222 (internal only)
	WebsocketListen string // e.g. 0.0.0.0:8080 (internal only; pulsed proxies /ws); empty disables
	OperatorJWTPath string
	SystemAccount   string // SYS account public key
	SysAccountJWT   string // preloaded
	ResolverDir     string
	JetStreamDir    string
	MaxFileStore    int64 // bytes; 0 lets NATS pick
	MaxMemoryStore  int64 // bytes
	TLSCertFile     string
	TLSKeyFile      string
	// ExtraCerts are served before the main pair; the server picks a certificate by SNI (an ACME certificate for the
	// public hostname first, the internal leaf for "nats").
	ExtraCerts   []CertPair
	MaxPayload   int64 // bytes
	PingInterval string
	MaxPingsOut  int
}

// CertPair is one certificate and key file.
type CertPair struct {
	CertFile string
	KeyFile  string
}

// Defaults fills unset fields with production defaults.
func (p *Params) Defaults() {
	if p.ServerName == "" {
		p.ServerName = "pulse"
	}
	if p.ClientListen == "" {
		p.ClientListen = "0.0.0.0:4222"
	}
	if p.MonitorListen == "" {
		p.MonitorListen = "0.0.0.0:8222"
	}
	if p.MaxPayload == 0 {
		p.MaxPayload = 1 << 20
	}
	if p.MaxMemoryStore == 0 {
		p.MaxMemoryStore = 64 << 20
	}
	if p.PingInterval == "" {
		p.PingInterval = "30s" // Cloudflare drops idle websockets after 100 s
	}
	if p.MaxPingsOut == 0 {
		p.MaxPingsOut = 3
	}
}

func (p Params) validate() error {
	for name, v := range map[string]string{
		"OperatorJWTPath": p.OperatorJWTPath, "SystemAccount": p.SystemAccount, "SysAccountJWT": p.SysAccountJWT,
		"ResolverDir": p.ResolverDir, "JetStreamDir": p.JetStreamDir, "TLSCertFile": p.TLSCertFile, "TLSKeyFile": p.TLSKeyFile,
	} {
		if v == "" {
			return fmt.Errorf("natsconf: %s is required", name)
		}
	}
	if p.MaxPayload > 8<<20 {
		return errors.New("natsconf: max_payload above 8 MB is not supported")
	}
	return nil
}

var tmpl = template.Must(template.New("nats.conf").Funcs(template.FuncMap{"q": strconv.Quote}).Parse(
	`# Generated by pulsed init. Do not edit: changes are overwritten on the next init.
server_name: {{q .ServerName}}
listen: {{q .ClientListen}}
http: {{q .MonitorListen}}

max_payload: {{.MaxPayload}}
ping_interval: {{q .PingInterval}}
ping_max: {{.MaxPingsOut}}
write_deadline: "10s"
max_control_line: 4096

tls {
{{- if .ExtraCerts}}
  certs: [
{{- range .ExtraCerts}}
    { cert_file: {{q .CertFile}}, key_file: {{q .KeyFile}} }
{{- end}}
    { cert_file: {{q .TLSCertFile}}, key_file: {{q .TLSKeyFile}} }
  ]
{{- else}}
  cert_file: {{q .TLSCertFile}}
  key_file: {{q .TLSKeyFile}}
{{- end}}
  timeout: 5
}
{{if .WebsocketListen}}
websocket {
  listen: {{q .WebsocketListen}}
  no_tls: true
  compression: true
  handshake_timeout: "10s"
}
{{end}}
jetstream {
  store_dir: {{q .JetStreamDir}}
  max_memory_store: {{.MaxMemoryStore}}
{{- if gt .MaxFileStore 0}}
  max_file_store: {{.MaxFileStore}}
{{- end}}
}

operator: {{q .OperatorJWTPath}}
system_account: {{q .SystemAccount}}

resolver {
  type: full
  dir: {{q .ResolverDir}}
  allow_delete: true
  interval: "2m"
  timeout: "5s"
}

resolver_preload {
  {{.SystemAccount}}: {{q .SysAccountJWT}}
}
`))

// Render returns nats.conf contents.
func Render(p Params) ([]byte, error) {
	p.Defaults()
	if err := p.validate(); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	if err := tmpl.Execute(&b, p); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
