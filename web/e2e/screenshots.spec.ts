type Grant = { action: string; subject?: string; name?: string; stream?: string }

async function admin<T>(request: APIRequestContext, method: string, path: string, data?: unknown): Promise<T> {
  const res = await request.fetch(`${adminURL}/api/admin/v1${path}`, { method, headers: csrf, ...(data === undefined ? {} : { data }) })
  if (!res.ok()) throw new Error(`${method} ${path}: ${res.status()} ${await res.text()}`)
  const text = await res.text()
  return (text ? JSON.parse(text) : undefined) as T
}

const pick = <T,>(xs: T[]): T => xs[Math.floor(Math.random() * xs.length)]

