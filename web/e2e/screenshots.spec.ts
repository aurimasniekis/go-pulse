/** Starts the background page: every client connects over /ws and publishes at a few events per second for `ms`. */
async function startClients(page: Page, creds: Record<string, string>, ms: number): Promise<void> {
  await page.setContent('<!doctype html><title>pulse clients</title>')
  await page.addScriptTag({ content: readFileSync(bundle, 'utf8') })
  await page.evaluate(
    ({ wsURL, creds, ms }) => {
      type Conn = { publish: (s: string, t: string, d: unknown) => Promise<unknown>; subscribe: (f: string, o: unknown) => AsyncIterable<unknown> }
      const P = (globalThis as unknown as { Pulse: { connect: (o: unknown) => Promise<Conn> } }).Pulse
      const sleep = (n: number) => new Promise((r) => setTimeout(r, n))
      const pick = <T,>(xs: T[]): T => xs[Math.floor(Math.random() * xs.length)]
      const run = async () => {
        const c: Record<string, Conn> = {}
        for (const [name, cr] of Object.entries(creds)) c[name] = await P.connect({ servers: wsURL, creds: cr, source: name })
        void (async () => {
          for await (const _ of c['dashboard-browser'].subscribe('evt.>', { new: true })) void _
        })()
        void (async () => {
          for await (const _ of c['budget-agent'].subscribe('evt.finance.>', { durable: 'budget' }) as AsyncIterable<{ ack: () => void }>) _.ack()
        })()
        const rooms = ['living-room', 'bedroom', 'kitchen', 'office']
        const end = Date.now() + ms
        const start = Date.now()
        let temp = 21.2
        while (Date.now() < end) {
          // A slow wave plus noise, so the throughput chart has some shape (0.5–4 events per second).
          const wave = 1 + Math.sin(((Date.now() - start) / 240_000) * 2 * Math.PI)
          const n = Math.max(0, Math.round(wave * 1.5 + Math.random()))
          for (let i = 0; i < n; i++) {
            const r = Math.random()
            temp += (Math.random() - 0.5) * 0.2
            if (r < 0.45) {
              const room = pick(rooms)
              await c['home-assistant'].publish(`evt.home.thermostat.reading.${room}`, 'home.thermostat.reading.v1', {
                room,
                celsius: Math.round(temp * 10) / 10,
                target: 21.5,
                humidity: 40 + Math.round(Math.random() * 15),
              })
            } else if (r < 0.65) {
              const room = pick(rooms)
              await c['home-assistant'].publish(`evt.home.lights.switched.${room}`, 'home.lights.switched.v1', { room, on: Math.random() < 0.5, scene: pick(['evening', 'focus', 'off']) })
            } else if (r < 0.8) {
              const door = pick(['front', 'back', 'garage'])
              const action = pick(['opened', 'closed'])
              await c['door-bot'].publish(`evt.home.door.${action}.${door}`, `home.door.${action}.v1`, { door, battery: 70 + Math.round(Math.random() * 30) })
            } else if (r < 0.9) {
              await c['media-indexer'].publish(`evt.media.photo.indexed.${pick(['holidays', 'family', 'garden'])}`, 'media.photo.indexed.v1', {
                file: `IMG_${4000 + Math.round(Math.random() * 5000)}.HEIC`,
                faces: Math.round(Math.random() * 3),
                width: 4032,
                height: 3024,
              })
            } else {
              await c['budget-agent'].publish('evt.agents.task.completed.budget-review', 'agents.task.completed.v1', {
                agent: 'budget-agent',
                task: pick(['categorise transactions', 'check subscriptions', 'monthly summary']),
                duration_ms: 800 + Math.round(Math.random() * 9000),
                ok: Math.random() > 0.05,
              })
            }
          }
          await sleep(1000)
        }
      }
      ;(globalThis as unknown as { __done: Promise<void> }).__done = run()
    },
    { wsURL, creds, ms },
  )
}

const repos = ['go-pulse', 'home-lab', 'dotfiles', 'recipes']

async function sendGithub(request: APIRequestContext, secret: string): Promise<void> {
  const event = Math.random() < 0.7 ? 'push' : 'pull_request'
  const repo = pick(repos)
  const body = JSON.stringify(
    event === 'push'
      ? { ref: 'refs/heads/main', repository: { full_name: `octo-home/${repo}` }, pusher: { name: 'octo-home' }, commits: [{ message: pick(['fix: tidy config', 'feat: new scene', 'docs: readme']) }] }
      : { action: pick(['opened', 'closed', 'synchronize']), number: 10 + Math.round(Math.random() * 90), repository: { full_name: `octo-home/${repo}` } },
  )
  const sig = createHmac('sha256', secret).update(body).digest('hex')
  const res = await request.post(`${publicURL}/hooks/github`, {
    headers: { 'Content-Type': 'application/json', 'X-GitHub-Event': event, 'X-GitHub-Delivery': randomUUID(), 'X-Hub-Signature-256': `sha256=${sig}` },
    data: body,
  })
  expect(res.status()).toBe(202)
}

async function sendStripe(request: APIRequestContext, secret: string): Promise<void> {
  const id = `evt_${createHash('sha256').update(randomUUID()).digest('hex').slice(0, 24)}`
  const body = JSON.stringify({ id, type: 'invoice.paid', data: { object: { customer_name: pick(['Electricity', 'Internet', 'Gym', 'Cloud storage']), amount_paid: Math.round(Math.random() * 9000) + 500, currency: 'eur' } } })
  const t = Math.floor(Date.now() / 1000)
  const sig = createHmac('sha256', secret).update(`${t}.${body}`).digest('hex')
  const res = await request.post(`${publicURL}/hooks/stripe`, { headers: { 'Content-Type': 'application/json', 'Stripe-Signature': `t=${t},v1=${sig}` }, data: body })
  expect(res.status()).toBe(202)
}

async function sendWeather(request: APIRequestContext, token: string): Promise<void> {
  const res = await request.post(`${publicURL}/api/v1/publish/evt.weather.station.observed.balcony`, {
    headers: { Authorization: `Bearer ${token}`, 'Ce-Type': 'weather.station.observed.v1', 'Ce-Source': 'weather-station', 'Content-Type': 'application/json' },
    data: { celsius: 11 + Math.round(Math.random() * 40) / 10, wind_kmh: Math.round(Math.random() * 25), rain_mm: 0 },
  })
  expect(res.status()).toBe(201)
}

